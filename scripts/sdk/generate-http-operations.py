#!/usr/bin/env python3
"""Generate actual method/path dispatch registries for public Go/TS/Java REST SDKs."""
import argparse
import json
import subprocess
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
OPS = sorted((op['operationId'], method.upper(), path)
             for path, item in json.loads((ROOT/'schemas/openapi.yaml').read_text()).get('paths',{}).items()
             for method, op in item.items() if method in {'get','post','put','patch','delete'})

def outputs():
    go = ['// Code generated by scripts/sdk/generate-http-operations.py. DO NOT EDIT.', 'package neverapi', '',
          'var Operations = map[string]Operation{']
    ts = ['// Code generated by scripts/sdk/generate-http-operations.py. DO NOT EDIT.',
          'export const OPERATIONS = {']
    java = ['// Code generated by scripts/sdk/generate-http-operations.py. DO NOT EDIT.',
            'package ru.neverlauncher.api;', 'import java.util.Map;', 'import java.util.HashMap;', 'public final class Operations {',
            '  private Operations() {}', '  public record Operation(String method, String path) {}',
            '  public static final Map<String, Operation> ALL = build();',
            '  private static Map<String, Operation> build() {',
            '    Map<String, Operation> result = new HashMap<>();']

    for n,(name,method,path) in enumerate(OPS):
        go.append(f'    {json.dumps(name)}: {{Method: {json.dumps(method)}, Path: {json.dumps(path)}}},')
        ts.append(f'  {json.dumps(name)}: {{ method: {json.dumps(method)}, path: {json.dumps(path)} }},')
        # Разделяйте сгенерированный реестр на небольшие методы: выражение
        # Map.ofEntries более чем с 450 аргументами может на минуты остановить вывод
        # типов javac. Обычные вызовы put компилируются за ограниченное предсказуемое
        # время на Java 17/21.
        java.append(f'    result.put({json.dumps(name)},new Operation({json.dumps(method)},{json.dumps(path)}));')
    go += ['}', '']; ts += ['} as const;', 'export type OperationId = keyof typeof OPERATIONS;', '']
    java += ['    if (result.size() != '+str(len(OPS))+') throw new IllegalStateException("duplicate OpenAPI operation ID");',
             '    return Map.copyOf(result);', '  }', '}', '']
    return {'sdk/api/go/operations_generated.go': subprocess.run(['gofmt'], input='\n'.join(go).encode(),capture_output=True,check=True).stdout.decode(),
            'sdk/api/typescript/operations.generated.ts': '\n'.join(ts),
            'sdk/java/http-client/src/main/java/ru/neverlauncher/api/Operations.java': '\n'.join(java)}

if __name__ == '__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    for rel,body in outputs().items():
        dest=ROOT/rel
        if a.check:
            if not dest.exists() or dest.read_text()!=body:raise SystemExit(f'generated SDK drift: {rel}')
        else: dest.parent.mkdir(parents=True,exist_ok=True);dest.write_text(body)
    print(f'{len(OPS)} OpenAPI operations: generated SDK registries {"checked" if a.check else "written"}')

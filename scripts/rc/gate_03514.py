#!/usr/bin/env python3
"""Fail-closed 0.35.14 RC integration gate for actual test runs.

Inputs MUST be generated by live processes and are read from exact-commit CI
artifacts. The gate checks identity, scope, hashes and the required negative
native checks. It does NOT upgrade RC evidence into real Minecraft, stable
publication, platform notarization, disaster recovery or GA certification.
"""
import argparse
import json
from pathlib import Path
import re
import sys

REQUIRED_NATIVE={
    'binary-version-and-runtime-cli',
    'signed-transactional-http-download-and-independent-sha256',
    'installed-signature-and-file-verification',
    'warm-update-without-network-download',
    'corrupt-file-rejected-by-native-verifier',
    'real-transactional-repair-and-independent-sha256',
    'wrong-trust-root-denied',
    'modified-signed-manifest-denied',
}
PLATFORMS={'linux','windows','darwin'}

class GateBlocked(RuntimeError):
    pass


def need(condition, message):
    if not condition:
        raise GateBlocked(message)


def digest_ok(value):
    return isinstance(value,str) and re.fullmatch('[a-f0-9]{64}',value) is not None


def load_exact(path: Path):
    need(path.is_file() and not path.is_symlink() and path.stat().st_size <= 512*1024,
         'missing, symlinked or oversized evidence')
    with path.open(encoding='utf-8') as stream:
        data=json.load(stream)
    need(isinstance(data,dict), 'evidence must be an object')
    return data


def verify(native_dir: Path, desktop_dir: Path, backend_file: Path, commit: str, version: str):
    need(version == '0.35.14' and re.fullmatch('[a-f0-9]{40}',commit) is not None,
         'RC expects exact version and complete commit SHA')
    native=[]
    desktop=[]
    for system in sorted(PLATFORMS):
        nr=load_exact(native_dir/(system+'.json'))
        need(nr.get('schemaVersion')=='neverlauncher.rc.native.v1' and nr.get('version')==version
             and nr.get('status')=='passed' and nr.get('simulated') is False and nr.get('platform')==system
             and nr.get('commit')==commit,
             'native evidence mismatch for '+system)
        need(set(nr.get('checks',[])) >= REQUIRED_NATIVE and len(nr['checks'])==len(set(nr['checks'])),
             'missing actual runtime operations on '+system)
        need(all(digest_ok(nr.get(field)) for field in ('runtimeSha256','signerSha256','signedFixtureSha256'))
             and isinstance(nr.get('fixtureBytes'),int) and nr['fixtureBytes']>=128*1024,
             'missing native executable/fixture fingerprints')
        need('not Minecraft/GUI E2E' in nr.get('certificationScope',''),
             'native test must not claim live game certification')
        native.append({'os':system,'runtimeSha256':nr['runtimeSha256'],'checks':len(nr['checks'])})
        dr=load_exact(desktop_dir/(system+'.json'))
        need(dr.get('schemaVersion')=='neverlauncher.rc.desktop-build.v1' and dr.get('version')==version
             and dr.get('status')=='passed' and dr.get('simulated') is False
             and dr.get('commit')==commit and dr.get('platform')==system,
             'Desktop compiled artifact mismatch for '+system)
        need(digest_ok(dr.get('binarySha256')) and digest_ok(dr.get('frontendSha256'))
             and isinstance(dr.get('binarySizeBytes'),int) and dr['binarySizeBytes']>1_000_000
             and isinstance(dr.get('frontendAssets'),int) and dr['frontendAssets']>=2,
             'missing actual compiled Desktop bundle')
        desktop.append({'os':system,'binarySha256':dr['binarySha256'],'frontendSha256':dr['frontendSha256']})
    backend=load_exact(backend_file)
    need(backend.get('schemaVersion')=='neverlauncher.owner-player-http-acceptance.v1'
         and backend.get('version')==version and backend.get('status')=='local-loopback-passed'
         and backend.get('realBackend') is True and backend.get('realMinecraftCertification') is False
         and backend.get('nativeDesktopVerified') is False and backend.get('stablePublicationVerified') is False,
         'missing true disposable owner/player Backend E2E')
    checks=backend.get('checks',[])
    need(isinstance(checks,list) and len(checks)>=8
         and 'refresh-rotation-and-logout-revocation' in checks
         and 'unpublished-or-workspace-content-not-served' in checks
         and 'unauthenticated-admin-mutation-denied' in checks,
         'Backend acceptance lacked security negative checks')
    return {'schemaVersion':'neverlauncher.rc.verification.v1','version':version,'commit':commit,
            'status':'rc-source-checks-passed','native':native,'desktop':desktop,
            'backendChecks':len(checks),'realMinecraftCertified':False,
            'fullDisasterRecoveryCertified':False,'operatorSigned':False,
            'releaseApproval':'NOT-GA: requires protected runtime, deployment, security and DR certification'}


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--native-dir',type=Path,required=True)
    parser.add_argument('--desktop-dir',type=Path,required=True)
    parser.add_argument('--backend',type=Path,required=True)
    parser.add_argument('--commit',required=True)
    parser.add_argument('--output',type=Path,required=True)
    a=parser.parse_args()
    a.output.unlink(missing_ok=True)
    try:
        result=verify(a.native_dir,a.desktop_dir,a.backend,a.commit,'0.35.14')
        a.output.parent.mkdir(parents=True,exist_ok=True)
        a.output.write_text(json.dumps(result,indent=2,sort_keys=True)+'\n')
    except (GateBlocked,ValueError,OSError,KeyError,TypeError) as exc:
        print('0.35.14 RC blocked: '+str(exc),file=sys.stderr)
        return 3
    print('0.35.14 source RC passed. Live Minecraft, protected production and DR are NOT certified.')
    return 0

if __name__=='__main__':
    sys.exit(main())
